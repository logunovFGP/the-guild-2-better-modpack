function CheckC(Name, Value)
	if Value == nil then
		LogMessage("@MISSING_CONSTANT #E MISSING CONSTANT: " .. Name)
	elseif type(Value) == "number" or type(Value) == "string" then
		LogMessage("@OK_CONSTANT " .. Name .. " = " .. Value)
	else
		LogMessage("@OK_CONSTANT " .. Name .. " = <" .. type(Value) .. ">")
	end
end

